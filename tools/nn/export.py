"""Writes the trained weights as Rust constants.

Run: python3 tools/nn/export.py tools/nn/weights.json crates/cwld-decoder/src/neural_weights.rs
"""
import json
import sys


def arr(name, a):
    flat = [x for row in a for x in row] if isinstance(a[0], list) else a
    return f"pub const {name}: [f32; {len(flat)}] = [" + ", ".join(repr(float(x)) for x in flat) + "];\n"


w = json.load(open(sys.argv[1]))
out = "//! Weights of the small key-down network. Generated by tools/nn/export.py from the result of\n//! tools/nn/train.py (synthetic CW of CWLD's own generator); do not edit by hand.\n\n"
out += f"pub const W: usize = {w['w']};\npub const BACK: usize = {w['back']};\npub const STEP: usize = {w['step']};\npub const PRIOR_LOGIT: f32 = {w['prior_logit']!r};\n"
out += f"pub const INPUTS: usize = {len(w['w1'])};\npub const H1: usize = {len(w['b1'])};\npub const H2: usize = {len(w['b2'])};\n"
out += arr("W1", w["w1"]) + arr("B1", w["b1"]) + arr("W2", w["w2"]) + arr("B2", w["b2"]) + arr("W3", w["w3"]) + arr("B3", w["b3"])
open(sys.argv[2], "w").write(out)
